"""Write a SANITIZED schema summary (model/inspection/) of the deployed Northwind_FMCG semantic model.

The summary lists tables, columns, measures (with DAX), partition kinds and relationships only. It omits
model descriptions, partition source expressions (file paths) and annotations; raw TMDL stays under the
git-ignored state/raw-tmdl/ directory.

    python scripts/inspect_model.py                # fetch TMDL from the tenant (read-only)
    python scripts/inspect_model.py --from-raw     # reuse state/raw-tmdl/northwind_fmcg
"""

from __future__ import annotations

import argparse
import base64
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from scripts.lib.clients import build_clients  # noqa: E402
from scripts.lib.config import REPO_ROOT, load_config  # noqa: E402
from scripts.lib.manifest import Manifest  # noqa: E402
from scripts.lib.tmdl import parse_relationships, parse_table  # noqa: E402

RAW_DIR = REPO_ROOT / "state" / "raw-tmdl" / "northwind_fmcg"
OUT_DIR = REPO_ROOT / "model" / "inspection"


def fetch_raw() -> None:
    cfg = load_config()
    clients = build_clients(cfg)
    manifest = Manifest(cfg.manifest_path, cfg.tenant_id)
    workspace = manifest.find("Workspace", cfg.names.workspace)
    model = manifest.find("SemanticModel", cfg.names.semantic_model, workspace.id if workspace else None)
    if not (workspace and model):
        raise SystemExit("Deployment manifest has no workspace/semantic model; run deploy.py apply first")
    api = clients.fabric.api
    response = api.request("POST", f"workspaces/{workspace.id}/semanticModels/{model.id}/getDefinition", params={"format": "TMDL"}, json_body={}, ok=(200, 202))
    body = api.wait_for_operation(response) if response.status_code == 202 else response.json()
    for part in body["definition"]["parts"]:
        target = RAW_DIR / part["path"]
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(base64.b64decode(part["payload"]))


def summarize() -> dict:
    tables = []
    for path in sorted((RAW_DIR / "definition" / "tables").glob("*.tmdl")):
        table = parse_table(path.read_text(encoding="utf-8"))
        tables.append(table)
    relationships = parse_relationships((RAW_DIR / "definition" / "relationships.tmdl").read_text(encoding="utf-8"))
    return {
        "tables": [
            {
                "name": t.name,
                "hidden": t.hidden,
                "partitionKinds": sorted({f"{p.kind}/{p.mode}" for p in t.partitions}),
                "columns": [{"name": c.name, "dataType": c.data_type, "summarizeBy": c.summarize_by, "hidden": c.hidden, "calculated": c.calculated} for c in t.columns],
                "measures": [{"name": m.name, "expression": m.expression, "formatString": m.format_string} for m in t.measures],
            }
            for t in tables
        ],
        "relationships": [{"from": r.from_column, "to": r.to_column, "crossFilter": r.cross_filter, "active": r.active} for r in relationships],
    }


def render_markdown(summary: dict) -> str:
    lines = [
        "# Northwind_FMCG semantic model: sanitized schema summary", "",
        "Generated by `scripts/inspect_model.py` from the TMDL returned by the Fabric `getDefinition` API for the deployed model.",
        "Model descriptions, Power Query sources (local file paths) and annotations are intentionally omitted.", "",
        "## Relationships", "", "| From | To | Cross-filter | Active |", "| --- | --- | --- | --- |",
    ]
    for r in summary["relationships"]:
        lines.append(f"| `{r['from']}` | `{r['to']}` | {r['crossFilter']} | {r['active']} |")
    lines += ["", "## Measures (explicit DAX)", ""]
    for t in summary["tables"]:
        for m in t["measures"]:
            lines += [f"### `{m['name']}` (table `{t['name']}`)", "", "```dax", m["expression"], "```", ""]
    lines += ["## Tables", ""]
    for t in summary["tables"]:
        visible_note = " (hidden)" if t["hidden"] else ""
        lines += [f"### `{t['name']}`{visible_note}", "", f"Partitions: {', '.join(t['partitionKinds']) or 'n/a'}", "",
                  "| Column | Type | Summarize by | Hidden | Calculated |", "| --- | --- | --- | --- | --- |"]
        for c in t["columns"]:
            lines.append(f"| {c['name']} | {c['dataType']} | {c['summarizeBy'] or '-'} | {c['hidden']} | {c['calculated']} |")
        lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--from-raw", action="store_true")
    args = parser.parse_args(argv)
    if not args.from_raw:
        fetch_raw()
    summary = summarize()
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "schema.json").write_text(json.dumps(summary, indent=2), encoding="utf-8")
    (OUT_DIR / "SCHEMA.md").write_text(render_markdown(summary), encoding="utf-8")
    print(f"{len(summary['tables'])} tables, {len(summary['relationships'])} relationships, "
          f"{sum(len(t['measures']) for t in summary['tables'])} explicit measures -> {OUT_DIR}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
